int	ft_isalnum(int c)
{
	unsigned char	uc;

	uc = (unsigned char)c;
	if ((uc >= '0' && uc <= '9') || (uc >= 'a' && uc <= 'z')
		|| (uc >= 'A' && uc <= 'Z'))
		return (1);
	return (0);
}
